import { expect, test, type Page } from '@playwright/test'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { installFake } from './fakeBackend'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.resolve(HERE, '../../docs/user-guide/images')
const SAMPLE = path.resolve(HERE, '../../docs/user-guide/sample/ACME_Motor_Policy_Wording_Sample.txt')
// Pages with the navigation menu are cropped to the content area (bigger text in the Word document); the menu itself is shown in a few full screenshots.
const FULL = new Set(['01-login', '02-platform-home', '10a-admin-workspace-home', '10-admin-home', '29-home-contributor', '35-home-user'])
// Toasts of earlier steps would be confusing, so they are hidden except in the pictures that are about the message itself.
const TOAST = new Set(['08-tenant-created', '23-collection-created', '27-access-saved'])
const shot = async (p: Page, name: string) => {
  await p.evaluate((hide) => { if (hide) document.documentElement.setAttribute('data-hide-toasts', '1'); else document.documentElement.removeAttribute('data-hide-toasts') }, !TOAST.has(name))
  await p.screenshot({ path: path.join(OUT, `${name}.png`), ...(FULL.has(name) ? {} : { clip: { x: 256, y: 0, width: 1024, height: 780 } }) })
  await p.evaluate(() => document.documentElement.removeAttribute('data-hide-toasts'))
}
const nav = (p: Page, label: string) => p.getByRole('navigation', { name: /navigation$/ }).first().getByRole('link', { name: label, exact: true }).click()
const dialog = (p: Page) => p.getByRole('dialog')
const settle = (p: Page) => p.waitForTimeout(500)

async function signIn(p: Page, email: string) {
  await expect(p.getByRole('heading', { name: 'UnityRAG' })).toBeVisible()
  await p.getByLabel('Email').fill(email)
  await p.getByLabel('Password').fill('Sample-Passw0rd!')
  await p.getByRole('button', { name: 'Sign in' }).click()
}
async function signOut(p: Page) {
  await p.getByRole('button', { name: 'User menu' }).click()
  await p.getByRole('menuitem', { name: 'Sign out' }).click()
  await expect(p).toHaveURL(/\/login/)
}

