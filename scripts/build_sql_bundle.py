"""Build the consolidated SQL scripts in database/ from the ordered migration
files in database/migrations/ (the single source of truth also used by Alembic).

Apply order for a manual install: extensions.sql (superuser), roles.sql
(superuser, after substituting passwords), then as rag_migration: schema.sql,
rls_policies.sql, indexes.sql, domain_tables_and_policies.sql (chat, AI
configuration, audit/analytics and evaluation tables with their RLS),
functions.sql, seed_data.sql.
"""
from pathlib import Path

DB = Path(__file__).resolve().parents[1] / "database"
M = DB / "migrations"
BUNDLES = {
    "extensions.sql": ["01_extensions.sql"],
    "roles.sql": ["02_roles.sql"],
    "schema.sql": ["03_platform_tenant.sql", "04_identity_access.sql", "05_document_management.sql",
                   "06_chunks_embeddings.sql"],
    "rls_policies.sql": ["07_rls_policies.sql"],
    "indexes.sql": ["08_search_indexes.sql"],
    "domain_tables_and_policies.sql": ["09_chat_conversations.sql", "10_ai_configuration.sql",
                                       "11_audit_analytics.sql", "12_evaluation.sql"],
    "functions.sql": ["13_security_functions.sql"],
    "seed_data.sql": ["14_seed_reference.sql"],
}
for name, parts in BUNDLES.items():
    body = [f"-- GENERATED by scripts/build_sql_bundle.py from database/migrations/{', '.join(parts)}\n"
            "-- Do not edit; edit the migration files.  Runs as one transaction (transaction-local\n"
            "-- set_config in the seed requires it).\nBEGIN;\n"]
    for p in parts:
        body.append(f"\n-- >>> {p}\n" + (M / p).read_text(encoding="utf-8"))
    body.append("\nCOMMIT;\n")
    (DB / name).write_text("".join(body), encoding="utf-8")
    print("wrote", name)
